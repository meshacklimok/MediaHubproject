from .models import Transactions

load_dotenv()  # make the .env values available to this module

logger = logging.getLogger(__name__)

# Daraja credentials, loaded from .env
SHORTCODE = os.getenv('SHORTCODE')
PASSKEY = os.getenv('PASSKEY')
BASE_URL = os.getenv('BASE_URL', 'https://sandbox.safaricom.co.ke')
CONSUMER_KEY = os.getenv('CONSUMER_KEY')
CONSUMER_SECRET = os.getenv('CONSUMER_SECRET')
# public URL (e.g. ngrok) that Safaricom can reach to deliver the payment result
CALLBACK_URL = os.getenv('CALLBACK_URL', '')

# M-Pesa reports times in Kenyan time
NAIROBI_TZ = ZoneInfo('Africa/Nairobi')
REQUEST_TIMEOUT = 30  # seconds


def generate_password(timestamp):
    # password required by Daraja: base64(shortcode + passkey + timestamp)
    return base64.b64encode(f'{SHORTCODE}{PASSKEY}{timestamp}'.encode()).decode()


# MPESA API - authorization to get an access token
def generate_access_token():
    auth_url = f'{BASE_URL}/oauth/v1/generate?grant_type=client_credentials'
    response = requests.get(auth_url, auth=(CONSUMER_KEY, CONSUMER_SECRET), timeout=REQUEST_TIMEOUT)
    response.raise_for_status()
    return response.json().get('access_token')


def normalize_phone(phone):
    # accept 07XXXXXXXX, 01XXXXXXXX, +2547XXXXXXXX or 2547XXXXXXXX and return 2547XXXXXXXX
    phone = (phone or '').strip().replace(' ', '').lstrip('+')
    if phone.startswith('0'):
        phone = '254' + phone[1:]
    if len(phone) == 12 and phone.startswith('254') and phone.isdigit():
        return phone
    return None


# checkout page
def index(request):
    form = {}
    if request.user.is_authenticated:  # prefill from the logged-in user's profile
        form = {'name': request.user.get_full_name() or request.user.username, 'email': request.user.email}
    return render(request, 'mediampesa/index.html', {'form': form})


'''
1. Accept post data (phone, amount, name and email)
2. Create a pending transaction in the database
3. Generate the access token
4. Generate the password + timestamp
5. Send the STK push request to Safaricom via the Daraja API endpoint
6. Save the CheckoutRequestID generated by Safaricom to identify this transaction
7. Redirect the user to a waiting page while they enter their PIN
'''
@require_POST
def stk_push(request):
    phone = normalize_phone(request.POST.get('phone'))
    name = request.POST.get('name', '').strip()
    email = request.POST.get('email', '').strip()
    try:
        amount = int(request.POST.get('amount', ''))
    except ValueError:
        amount = 0

    errors = []
    if not phone:
        errors.append("Enter a valid Safaricom number, e.g. 0712345678.")
    if amount < 1:
        errors.append("Amount must be a whole number of at least KES 1.")
    if errors:
        return render(request, 'mediampesa/index.html', {'errors': errors, 'form': request.POST}, status=400)

    transaction = Transactions.objects.create(
        phone_number=phone,
        amount=amount,
        status="Pending",
        description="Awaiting status result",
        name=name,
        email=email,
    )

    timestamp = datetime.now(NAIROBI_TZ).strftime('%Y%m%d%H%M%S')
    payload = {
        "BusinessShortCode": SHORTCODE,
        "Password": generate_password(timestamp),
        "Timestamp": timestamp,
        "TransactionType": "CustomerPayBillOnline",
        "Amount": amount,  # Daraja only accepts whole numbers
        "PartyA": phone,
        "PartyB": SHORTCODE,
        "PhoneNumber": phone,
        # Safaricom posts the payment result here
        "CallBackURL": CALLBACK_URL.rstrip('/') + reverse('mediampesa:callback'),
        "AccountReference": f"Transaction_{transaction.id}",
        "TransactionDesc": "Payment for Services",
    }

    try:
        headers = {'Authorization': f'Bearer {generate_access_token()}'}
        response = requests.post(f'{BASE_URL}/mpesa/stkpush/v1/processrequest',
                                 json=payload, headers=headers, timeout=REQUEST_TIMEOUT)
        response_data = response.json()
    except (requests.RequestException, ValueError) as e:
        logger.exception("STK push request failed")
        transaction.status = "Failed"
        transaction.description = f"Could not reach M-Pesa: {e}"
        transaction.save()
        return redirect('mediampesa:payment_failed')

    # CheckoutRequestID is only present when the STK push was launched
    checkout_id = response_data.get('CheckoutRequestID')
    if not checkout_id:
        logger.warning("STK push rejected: %s", response_data)
        transaction.status = "Failed"
        transaction.description = response_data.get('errorMessage', "STK push rejected")
        transaction.save()
        return redirect('mediampesa:payment_failed')

    transaction.transaction_id = checkout_id
    transaction.description = response_data.get('ResponseDescription', "No Description")
    transaction.save()  # the user now has the PIN prompt on their phone

    return redirect('mediampesa:waiting_page', transaction_id=transaction.id)


def waiting_page(request, transaction_id):
    transaction = get_object_or_404(Transactions, id=transaction_id)
    return render(request, 'mediampesa/waiting.html', {'transaction': transaction})


def send_receipt_email(transaction):
    subject = "Payment Receipt Confirmation"
    message = (
        f"Dear {transaction.name},\n\n"
        f"Thank you for your payment of KES {transaction.amount}.\n"
        f"Your M-Pesa confirmation receipt is {transaction.mpesa_receipt_number}.\n\n"
        "Best regards,\n"
        "MediaHub"
    )
    html_message = (
        f"<p>Dear {transaction.name},</p>"
        f"<p>Thank you for your payment of KES {transaction.amount}.</p>"
        f"<p>Your M-Pesa confirmation receipt is <strong>{transaction.mpesa_receipt_number}</strong>.</p>"
        "<p>Best regards,<br>MediaHub</p>"
    )
    send_mail(subject, message, settings.DEFAULT_FROM_EMAIL, [transaction.email],
              html_message=html_message)


# Safaricom posts the result of every payment attempt to this view
@csrf_exempt
@require_POST
def callback(request):
    try:
        data = json.loads(request.body)
    except ValueError:
        return JsonResponse({"error": "Invalid JSON"}, status=400)

    logger.info("Received M-Pesa callback: %s", data)
    stk_callback = data.get('Body', {}).get('stkCallback', {})
    result_code = stk_callback.get('ResultCode')
    result_desc = stk_callback.get('ResultDesc', '')
    checkout_id = stk_callback.get('CheckoutRequestID')

    transaction = Transactions.objects.filter(transaction_id=checkout_id).first() if checkout_id else None
    if not transaction:
        # still acknowledge so Safaricom doesn't keep retrying
        return JsonResponse({"ResultCode": 0, "ResultDesc": "Unknown transaction"})

    if result_code == 0:  # 0 means the user paid
        # CallbackMetadata.Item is a list of {"Name": ..., "Value": ...}
        items = {item.get('Name'): item.get('Value')
                 for item in stk_callback.get('CallbackMetadata', {}).get('Item', [])}
        transaction.mpesa_receipt_number = items.get('MpesaReceiptNumber')
        if items.get('Amount') is not None:
            transaction.amount = items['Amount']
        if items.get('TransactionDate'):
            transaction.transaction_date = datetime.strptime(
                str(items['TransactionDate']), '%Y%m%d%H%M%S').replace(tzinfo=NAIROBI_TZ)
        transaction.status = "Success"
        transaction.description = "Payment Successful"
        transaction.save()

        if transaction.email:
            try:
                send_receipt_email(transaction)
            except Exception:
                # a mail failure shouldn't fail the callback; the payment is already recorded
                logger.exception("Failed to send receipt email for transaction %s", transaction.id)
    elif result_code == 1032:
        transaction.status = "Cancelled"
        transaction.description = "Transaction cancelled by user"
        transaction.save()
    else:
        # any other non-zero code (insufficient funds, wrong PIN, timeout...) is a failure
        transaction.status = "Failed"
        transaction.description = result_desc
        transaction.save()

    return JsonResponse({"ResultCode": 0, "ResultDesc": "Accepted"})


'''
on STK prompt the transaction status is Pending
on successful payment the status is Success
on failure the status is Failed
on cancellation the status is Cancelled
'''
def check_status(request, transaction_id):
    transaction = Transactions.objects.filter(id=transaction_id).first()
    if not transaction:
        return JsonResponse({"status": "NotFound", "message": "Transaction not found"}, status=404)

    messages = {
        "Success": "Payment Successful",
        "Failed": "Payment Failed",
        "Cancelled": "Transaction was Cancelled",
    }
    status = transaction.status if transaction.status in messages else "Pending"
    return JsonResponse({"status": status,
                         "message": messages.get(status, "Transaction still being processed.")})


